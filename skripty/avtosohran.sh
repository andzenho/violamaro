#!/bin/sh
# Авто-сохранение рабочей копии. Вызывается Stop-хуком (.claude/settings.json)
# в конце каждого ответа ассистента.
#
# Зачем. Машина сессии временная: незакоммиченное живёт только в рабочей копии
# и пропадает вместе с контейнером. Правки по имени продукта провисели три
# сессии только потому, что везло.
#
# Токены. Скрипт не стоит ни одного: модель в нём не участвует. Поэтому он
# МОЛЧИТ при успехе — вывод хука попадает в контекст сессии, а «сохранил» в
# каждом ответе это мусор. Говорит только когда что-то пошло не так.
#
# Чего не делает НИКОГДА:
#   • не коммитит в main — источник правды меняется только по решению продюсера;
#   • не сливает ветки и не разрешает расхождения;
#   • не роняет работу: любая ошибка внутри — это выход 0 и тишина.
#
# Проверить руками: sh skripty/avtosohran.sh --shumno

cd "${CLAUDE_PROJECT_DIR:-.}" 2>/dev/null || exit 0
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || exit 0

export GIT_TERMINAL_PROMPT=0

# --shumno: печатать и при успехе. Только для ручной проверки.
shumno=0
[ "$1" = "--shumno" ] && shumno=1

skazat() { [ "$shumno" = "1" ] && echo "$@"; }

# Нечего сохранять — молча выходим. Это самый частый случай.
if [ -z "$(git status --porcelain 2>/dev/null)" ]; then
    skazat "[авто] изменений нет."
    exit 0
fi

vetka=$(git symbolic-ref --short -q HEAD) || {
    echo "[авто] HEAD отцеплён — не коммичу. Разберись руками, правки не сохранены."
    exit 0
}

if [ "$vetka" = "main" ]; then
    echo "[авто] мы на main — не коммичу туда автоматически."
    echo "[авто] Заведи ветку под задачу, иначе правки не сохранятся."
    exit 0
fi

# Сообщение собираем из самих файлов: имена и дата. Без модели, без выдумок.
vsego=$(git status --porcelain | wc -l | tr -d ' ')
# cut -c4- берёт путь целиком: awk '{print $NF}' терял бы имена с пробелами.
imena=$(git status --porcelain | cut -c4- | head -2 | tr '\n' '|' | sed 's/|$//; s/|/, /g')
[ "$vsego" -gt 2 ] && imena="$imena (+$((vsego - 2)))"
soobshchenie="авто $(date '+%d.%m %H:%M') · $imena"

git add -A || exit 0
if ! git commit --quiet -m "$soobshchenie" 2>/dev/null; then
    skazat "[авто] коммит не прошёл (возможно, нечего коммитить после add)."
    exit 0
fi
skazat "[авто] закоммичено: $soobshchenie"

# Пуш. Сеть может лежать — это не повод шуметь в контекст каждый раз:
# коммит уже сделан, работа не потеряна, следующий вызов допушит.
if git push --quiet -u origin "$vetka" 2>/dev/null; then
    skazat "[авто] запушено в origin/$vetka."
    exit 0
fi

sleep 2
if git push --quiet -u origin "$vetka" 2>/dev/null; then
    skazat "[авто] запушено в origin/$vetka со второй попытки."
    exit 0
fi

echo "[авто] закоммичено локально, но пуш в origin/$vetka не прошёл (сеть?)."
echo "[авто] Работа не потеряна, но живёт только на этой машине. Скажи — запушу руками."
exit 0
